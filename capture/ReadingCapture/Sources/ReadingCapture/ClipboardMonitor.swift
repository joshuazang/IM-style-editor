import AppKit

/// Poll only the change counter while enabled. Read text only for allowed apps.
@MainActor final class ClipboardMonitor {
    private var timer: Timer?
    private var seen = 0
    var allowed: Set<String> = []
    var receive: ((String, NSRunningApplication) -> Void)?
    func start() {
        stop(); seen = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.25, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        timer?.tolerance = 0.05
    }
    func stop() { timer?.invalidate(); timer = nil }
    private func poll() {
        let board = NSPasteboard.general, count = board.changeCount
        guard count != seen else { return }; seen = count
        guard let app = NSWorkspace.shared.frontmostApplication, let bundle = app.bundleIdentifier, allowed.contains(bundle) else { return }
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]),
              let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf8.count <= 1_000_000,
              board.changeCount == count else { return }
        receive?(text, app)
    }
}
