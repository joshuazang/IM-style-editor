const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),crypto=require('node:crypto');
const context=vm.createContext({crypto,btoa,Ed:value=>value?.slice(0,10)||'earlier'});
for(const file of ['note-format','message-transfer','reply-ui','message-merge'])vm.runInContext(fs.readFileSync(`next/src/${file}.js`,'utf8'),context);
const {imFormat:f,imMergeSelected:merge,imReplyTarget:target,imMessagesByDay:days}=vm.runInContext('({imFormat,imMergeSelected,imReplyTarget,imMessagesByDay})',context);
const plain=value=>JSON.parse(JSON.stringify(value));
const messages=[' A\n\n🙂 ','untouched','B\n@@IM:BUBBLE\n','C'].map((text,i)=>({id:f.newId(),text,reactions:i%2?['📓']:['⭐'],createdAt:`2026-11-0${i+1}T12:00:00Z`,copied:true,exported:true}));
messages[2].replyTo={id:messages[1].id,noteId:'note',text:messages[1].text};
messages[3].forwarding={sourceMessageId:f.newId(),sourceNoteId:'archive'};
messages[3].custom={precious:'metadata'};
const original=JSON.stringify(messages),settings={pinnedMessageIds:[messages[2].id,messages[1].id,messages[3].id],reactionOrder:['⭐','📓']};
const selection=new Set([messages[3].id,messages[0].id,messages[2].id]);
const result=merge(messages,settings,selection,'note');
assert.equal(result.messages.length,2);
assert.equal(result.messages[0].id,messages[0].id);
assert.equal(result.messages[0].createdAt,messages[0].createdAt);
assert.equal(result.messages[0].text,[messages[0],messages[2],messages[3]].map(m=>m.text).join('\n\n'));
assert.equal(result.messages[1],messages[1]);
assert.deepEqual(plain(result.messages[0].reactions),['⭐','📓']);
assert.deepEqual(plain(result.settings.pinnedMessageIds),[messages[0].id,messages[1].id]);
assert.equal(result.messages[0].edited,true);
for(const flag of ['copied','exported'])assert.equal(Object.hasOwn(result.messages[0],flag),false);
assert.equal(JSON.stringify(messages),original);
assert.deepEqual(settings.pinnedMessageIds,[messages[2].id,messages[1].id,messages[3].id]);
for(const message of messages.filter(m=>selection.has(m.id))){
 assert.equal(target(result.messages,{id:message.id,noteId:'note',text:message.text},'note'),result.messages[0]);
 assert.equal(target(result.messages,{id:message.id,noteId:'wrong-note',text:'wrong'},'note'),undefined);
}
assert.equal(target(result.messages,{id:messages[3].forwarding.sourceMessageId,noteId:'archive'},'note'),result.messages[0]);
assert.equal(result.messages[0].mergeSources[1].replyTo.text,messages[1].text);
assert.equal(result.messages[0].mergeSources[2].custom.precious,'metadata');
assert.ok(result.messages[0].mergeSources.every(m=>!Object.hasOwn(m,'text')));
const text=f.portable(result.messages,result.settings,'unchanged draft');
const note={content:{text}};
assert.deepEqual(plain(f.readMessages(note)),plain(result.messages));
assert.equal(f.readDraft(note),'unchanged draft');
const again=merge(result.messages,result.settings,new Set(result.messages.map(m=>m.id)),'note');
assert.equal(target(again.messages,{id:messages[3].id,noteId:'note'},'note'),again.messages[0]);
assert.equal(again.messages[0].mergeSources.length,4,'repeated merges do not accumulate duplicate origin metadata');
const transfer=vm.runInContext('imTransfer',context);
const exported=transfer.read(transfer.create(again.messages,again.settings,'note'));
const imported=transfer.merge([],exported).messages;
assert.equal(target(imported,{id:messages[3].id,noteId:'note'},'destination'),imported[0]);
assert.throws(()=>merge(messages,settings,new Set([messages[0].id]),'note'),/at least two/);
assert.deepEqual(plain([...days(messages)]),messages.map((m,i)=>[`2026-11-0${i+1}`,[m.id]]));
console.log('PASS: noncontiguous merge order, exact text, sparse statuses, immutable sources, tags, pins, quoted metadata, nested reply destinations, note isolation and format round trip');
