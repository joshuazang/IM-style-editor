const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const api=vm.runInNewContext(fs.readFileSync('next/src/host-bridge.js','utf8')+';({track:imTrackHostReply,release:imReleaseHostReply})');
const bridge={sentMessages:[]};let calls=0;
for(let i=0;i<1000;i++)api.track(bridge,{action:'key-down',messageId:String(i),data:{key:'a'}},undefined);
assert.equal(bridge.sentMessages.length,0);
const secret='Full private note body '.repeat(10000);
api.track(bridge,{action:'stream-context-item',messageId:'stream',data:{}},()=>calls++);
const stream=bridge.sentMessages[0];stream.callback({item:{content:{text:secret}}});stream.callback({item:{content:{text:'changed'}}});
assert.equal(calls,2);assert.equal(bridge.sentMessages.length,1);
const shared=()=>calls++;
api.track(bridge,{action:'save-items',messageId:'save-1',data:{items:[{content:{text:secret}}]}},shared);
api.track(bridge,{action:'save-items',messageId:'save-2',data:{items:[{content:{text:secret}}]}},shared);
assert.ok(!JSON.stringify(bridge.sentMessages).includes(secret));
bridge.sentMessages.find(record=>record.messageId==='save-1').callback({});
assert.equal(calls,3);assert.equal(bridge.sentMessages.length,2,'Same callback on a different request must survive');
bridge.sentMessages.find(record=>record.messageId==='save-2').callback({error:'rejected'});
assert.equal(calls,4);assert.equal(bridge.sentMessages.length,1);
const timedOut=()=>assert.fail('Expired callback must be released');
api.track(bridge,{action:'save-items',messageId:'timeout',data:{items:[{content:{text:secret}}]}},timedOut);
api.release(bridge,timedOut);assert.equal(bridge.sentMessages.length,1);
api.track(bridge,{action:'save-items',messageId:'throws',data:{}},()=>{throw new Error('callback failed');});
assert.throws(()=>bridge.sentMessages.find(record=>record.messageId==='throws').callback({}),/callback failed/);
assert.equal(bridge.sentMessages.length,1);assert.equal(bridge.sentMessages[0],stream);
console.log('PASS: no outgoing note-body history, no fire-and-forget history, one-off replies/errors/timeouts release callbacks, streams and shared callback identities remain correct');
