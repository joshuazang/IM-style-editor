const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),crypto=require('node:crypto');
const f=vm.runInNewContext(fs.readFileSync('shared/core/note-format.js','utf8')+';imFormat',{crypto,btoa});
const clear=vm.runInNewContext(fs.readFileSync('shared/core/message-statuses.js','utf8')+';imClearStatuses',{imFormat:f});
const a={id:f.newId(),text:'Keep exact text\n\n🙂',createdAt:'2026-11-01T12:00:00Z',reactions:['⭐'],copied:true,exported:true,edited:true,sourceRefs:[['source',f.newId()]],imported:true};
const b={...a,id:f.newId(),replyTo:{id:a.id,noteId:'current',text:a.text}};
const c={...a,id:f.newId(),replyTo:{id:b.id,noteId:'current',text:b.text}};
const records=[a,b,c],snapshot=JSON.stringify(records),standalone=clear(records,['reply'],new Set([b.id]));
assert.equal(standalone[0],a);assert.equal(standalone[2],c);assert.ok(!Object.hasOwn(standalone[1],'replyTo'));
const expected={...b};delete expected.replyTo;assert.equal(JSON.stringify(standalone[1]),JSON.stringify(expected));assert.equal(JSON.stringify(records),snapshot);
const all=clear(records,new Set(['reply']));assert.equal(all[0],a);assert.ok(!Object.hasOwn(all[1],'replyTo')&&!Object.hasOwn(all[2],'replyTo'));
const mixed=clear(records,['reply','copied'],new Set([b.id]));assert.ok(!Object.hasOwn(mixed[1],'replyTo')&&!Object.hasOwn(mixed[1],'copied'));assert.equal(mixed[1].sourceRefs,b.sourceRefs);assert.equal(mixed[1].edited,true);assert.equal(mixed[2],c);
assert.equal(clear(all,['reply']),all);assert.equal(clear(records,['reply'],new Set()),records);assert.equal(clear(records,['unknown']),records);
const draftReply={id:a.id,noteId:'current',text:a.text},saved=f.inspect(f.portable(standalone,{pinnedMessageIds:[b.id]},'Unsent draft',draftReply));
assert.ok(!Object.hasOwn(saved.messages[1],'replyTo'));assert.equal(saved.messages[2].replyTo.id,b.id);assert.equal(saved.reply.id,a.id);assert.equal(saved.draft,'Unsent draft');assert.equal(saved.settings.pinnedMessageIds[0],b.id);
const original=JSON.stringify([a,b]);
const result=clear([a,b],['copied','exported','edited','imported'],new Set([a.id]));
assert.equal(result[1],b);assert.equal(JSON.stringify([a,b]),original);
for(const flag of ['copied','exported','edited'])assert.ok(!Object.hasOwn(result[0],flag));
assert.ok(!Object.hasOwn(result[0],'imported')&&!Object.hasOwn(result[0],'importedStatusCleared'));assert.equal(result[0].sourceRefs,a.sourceRefs);assert.equal(result[0].text,a.text);assert.equal(result[0].reactions,a.reactions);
const parsed=f.inspect(f.portable(result,{pinnedMessageIds:[a.id]},'Draft'));
assert.ok(!f.isImported(parsed.messages[0]));assert.equal(parsed.draft,'Draft');assert.equal(parsed.messages[1].replyTo.id,a.id);
const transfer=vm.runInNewContext(fs.readFileSync('shared/core/message-transfer.js','utf8')+';imTransfer',{imFormat:f});
const payload=transfer.read(transfer.create([a],{},'source'));
const once=transfer.merge([],payload);const hidden=clear(once.messages,['imported']);
assert.equal(transfer.merge(hidden,payload).added.length,0);
const moved=transfer.merge([],transfer.read(transfer.create(hidden,{},'destination')));
assert.equal(moved.messages[0].imported,true);
const replyTarget=vm.runInNewContext(fs.readFileSync('shared/core/reply-record.js','utf8')+';imReplyTarget',{imFormat:f});
const rootId=f.newId(),origin={sourceNoteId:'original-note',sourceMessageId:rootId,forwardedAt:'2026-10-31T22:06:04.223Z'};
const forwarded={sourceNoteId:'intermediate-note',sourceMessageId:rootId,forwardedAt:'2026-11-01T17:26:33.975Z',previous:origin};
const historical=f.portable([{id:a.id,text:a.text,reactions:a.reactions}],{}).replace('@@IM:CONTENT',[
 `forwarding: ${JSON.stringify(forwarded)}`,
 `extra-metadata: ${JSON.stringify({importedStatusCleared:true,mergeSources:[{id:rootId,noteId:'merge-note',forwarding:forwarded},{id:rootId,noteId:'original-note',forwarding:origin}]})}`,
 '@@IM:CONTENT'
].join('\n'));
const legacyNote={content:{text:historical}};
const compact=f.readMessages(legacyNote)[0];
assert.equal(legacyNote.content.text,historical);
assert.equal(compact.imported,undefined);
assert.equal(compact.sourceRefs.length,2);
assert.equal(compact.text,a.text);
for(const noteId of ['original-note','intermediate-note'])assert.equal(replyTarget([compact],{id:rootId,noteId,text:'Old text'},'current'),compact);
assert.equal(replyTarget([compact],{id:rootId,noteId:'merge-note',text:'Old text'},'current'),undefined);
f.write(legacyNote,[compact],{});
assert.ok(legacyNote.content.text.length<historical.length/2);
assert.doesNotMatch(legacyNote.content.text,/forwarding|previous|forwardedAt|mergeSources|importedStatusCleared/);
const plainSource={id:rootId,text:'A source that had an ID collision',reactions:[]};
const originalPayload={ok:true,sourceNoteId:'original-note',messages:[plainSource]};
const importedCollision=transfer.merge([{...plainSource,text:'Different message, same ID'}],originalPayload).added[0];
assert.notEqual(importedCollision.id,rootId);
const twice=transfer.merge([], {ok:true,sourceNoteId:'intermediate-note',messages:[importedCollision]}).added[0];
const cleared=clear([twice],['imported'])[0];
assert.equal(replyTarget([cleared],{id:rootId,noteId:'original-note',text:'Old text'},'current'),cleared);
assert.equal(transfer.merge([cleared],originalPayload).added.length,0);
assert.equal(transfer.merge([f.editMessage(cleared,'Changed content')],originalPayload).added.length,1);
console.log('PASS: selective clearing, exact text/draft/pins/replies, physical removal of Imported and duplicate-safe re-import');
